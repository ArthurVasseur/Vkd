	// Factory: copy the template blob into out[], patch surfaceFlags.
	// out must point to a kAllocBlobSize-byte buffer.
	inline void MakeBlobCopy(uint8_t* out, const uint8_t* tmpl, uint32_t surfFlags)
	{
		std::memcpy(out, tmpl, kAllocBlobSize);
		// Patch surfaceFlags (LE u32 at offset kSurfFlagsOffset)
		out[kSurfFlagsOffset + 0] = static_cast<uint8_t>(surfFlags);
		out[kSurfFlagsOffset + 1] = static_cast<uint8_t>(surfFlags >> 8);
		out[kSurfFlagsOffset + 2] = static_cast<uint8_t>(surfFlags >> 16);
		out[kSurfFlagsOffset + 3] = static_cast<uint8_t>(surfFlags >> 24);
	}

	// surfFlags constants (confirmed via RE)
	static constexpr uint32_t kSurfaceFlagsDeviceLocal = 0x00002005;
	static constexpr uint32_t kSurfaceFlagsHostVisible = 0x20002005;
	static constexpr uint32_t kSurfaceFlagsInitA = 0x20002004;
	static constexpr uint32_t kSurfaceFlagsInitB = 0x2004200C;

	// The VA window PAL reserves for shader code and descriptor tables (see
	// AmdDevice::AllocateShaderWindowMemory).
	static constexpr uint64_t kShaderWindowBase = 0x100000000ull;
	static constexpr uint64_t kShaderWindowSize = 0x100000000ull;
	// GFX11 vertex attribute ring: the SPI_ATTRIBUTE_RING_SIZE AMDVLK programs (MEM_SIZE 7 = 8 x 64KB).
	static constexpr uint64_t kAttributeRingBytes = 512 * 1024;

	// Convenience: blob on stack for direct passing to AllocationDesc.
	struct AllocBlobBuffer
	{
		uint8_t data[kAllocBlobSize];
		const void* ptr() const
		{
			return data;
		}
	};

	inline AllocBlobBuffer MakeAllocBlobDeviceLocal()
	{
		AllocBlobBuffer b;
		MakeBlobCopy(b.data, kAllocBlobDeviceLocal, kSurfaceFlagsDeviceLocal);
		return b;
	}

	inline AllocBlobBuffer MakeAllocBlobHostVisible()
	{
		AllocBlobBuffer b;
		MakeBlobCopy(b.data, kAllocBlobDeviceLocal, kSurfaceFlagsHostVisible);
		return b;
	}

	inline AllocBlobBuffer MakeAllocBlobInit(uint32_t surfFlags)
	{
		AllocBlobBuffer b;
		MakeBlobCopy(b.data, kAllocBlobInit, surfFlags);
		return b;
	}

	// Init allocs with surf type 0x5 (0x20002005 / 0x00002005) fail if the 0x20002004
	// init template is only patched at +0x50 — KMD checks the tail. Use the 0x5 blob.
	inline AllocBlobBuffer MakeAllocBlobForSurfFlags(uint32_t surfFlags)
	{
		AllocBlobBuffer b;
		const uint8_t* tmpl = ((surfFlags & 0xFFu) == 0x05u) ? kAllocBlobDeviceLocal : kAllocBlobInit;
		MakeBlobCopy(b.data, tmpl, surfFlags);
		return b;
	}

	// wddm-dump [submit-records][re] (2026-10-07): across all 20 AMDVLK allocations the blob carries
	// the allocation size at +0x54, +0xA8, +0xB8 and +0x114 -- always equal to each other and to the
	// size actually mapped with D3DKMTMapGpuVirtualAddress. The templates above were captured from a
	// 4KB init alloc (kAllocBlobInit) and a 32MB device-local pool (kAllocBlobDeviceLocal); mapping any
	// other size without patching these leaves the KMD with a different allocation size than the GPU
	// VA mapping (Lock2 exposed only 4KB of a "64KB" IB, and the GPU page-faulted reading it).
	// +0x58 is the alignment: in AMDVLK's allocations always a power of two dividing the size
	// (0x1000 ... 0x200000). Capping it to a non-power-of-two size (e.g. 0x1E0000 for an 800x600
	// RGBA8 image) left the paging fence of that allocation unsignaled forever.
	static constexpr size_t kAllocBlobSizeOffsets[] = {0x54, 0xA8, 0xB8, 0x114};
	static constexpr size_t kAllocBlobAlignmentOffset = 0x58;

	inline void SetAllocBlobSize(AllocBlobBuffer& b, uint32_t sizeBytes)
	{
		for (size_t off : kAllocBlobSizeOffsets)
			std::memcpy(b.data + off, &sizeBytes, sizeof(sizeBytes));
		uint32_t alignment = 0;
		std::memcpy(&alignment, b.data + kAllocBlobAlignmentOffset, sizeof(alignment));
		const uint32_t sizePow2Divisor = sizeBytes & (~sizeBytes + 1u);
		if (alignment > sizePow2Divisor)
			std::memcpy(b.data + kAllocBlobAlignmentOffset, &sizePow2Divisor, sizeof(sizePow2Divisor));
	}

	inline AllocBlobBuffer MakeAllocBlobForSurfFlags(uint32_t surfFlags, uint32_t sizeBytes)
	{
		AllocBlobBuffer b = MakeAllocBlobForSurfFlags(surfFlags);
		SetAllocBlobSize(b, sizeBytes);
		return b;
	}
