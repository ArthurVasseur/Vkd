	// Graphics pipelines replayed from AMDVLK until Vkd compiles SPIR-V: the NGG ES (vertex) and PS
	// code AMDVLK produced for an exact VS/FS pair, and every register write AMDVLK's draw relies on,
	// in order -- the queue-init submit and the queue-state IB its per-submit preamble chains to (the
	// context AMDVLK restores through register shadowing, shared by every pipeline), then the command
	// buffer's draw state minus its compute clear of the target. GENERATED by
	// Amd/tools/gen_graphics_replay.py (spec: Amd/tools/graphics_replay.json) from wddm-dump
	// [draw][re]... captures (Amd/Src/WddmDump/Tests/DispatchRE.cpp). Patched fields are what depends
	// on the Vulkan state rather than on the pipeline: addresses, target extent, viewport, scissor,
	// cull mode, descriptor tables.
	enum class RegKind : uint8_t
	{
		Context,	   // SET_CONTEXT_REG, 0xA000 base
		Sh,			   // SET_SH_REG, 0x2C00 base (graphics)
		ShIndex,	   // SET_SH_REG_INDEX index 3: the CP ANDs the KMD's CU mask in
		Uconfig,	   // SET_UCONFIG_REG, 0xC000 base
		UconfigIndex2, // SET_UCONFIG_REG_INDEX index 2 (VGT_INDEX_TYPE)
	};

	enum class RegPatch : uint8_t
	{
		None,
		EsCodeLo,		   // ES code VA >> 8
		PsCodeLo,		   // PS code VA >> 8
		ColorBase,		   // color target VA >> 8
		ColorSize,		   // CB_COLOR0_ATTRIB2: (height - 1) | (width - 1) << 14
		AttributeRingBase, // attribute ring VA >> 16
		ShaderRingTable,   // 32-bit pointer to the shader-ring descriptor table (PAL's global table)
		SetTable0,		   // 32-bit pointer to descriptor set N's table
		SetTable1,
		SetTable2,
		SetTable3,
		TargetExtent,	   // screen/window scissor BR: width | height << 16
		VportXScale,	   // PA_CL_VPORT_*: viewport 0
		VportXOffset,
		VportYScale,
		VportYOffset,
		VportZScale,
		VportZOffset,
		VportZMin,		   // PA_SC_VPORT_ZMIN/ZMAX_0
		VportZMax,
		GbVertClip,		   // PA_CL_GB_*: guard band of viewport 0
		GbVertDisc,
		GbHorzClip,
		GbHorzDisc,
		ScreenOffset,	   // PA_SU_HARDWARE_SCREEN_OFFSET: centers the guard band on the viewport
		ScissorTl,		   // PA_SC_VPORT_SCISSOR_0_TL/BR: scissor 0
		ScissorBr,
		CullMode,		   // PA_SU_SC_MODE_CNTL bits 0-2: CULL_FRONT, CULL_BACK, FACE (1 = clockwise front)
		BaseVertex,		   // VS user data added to the vertex id: firstVertex / vertexOffset
		BaseInstance,	   // VS user data added to the instance id: firstInstance
		IndexType,		   // VGT_INDEX_TYPE bits 0-1: 0 = 16-bit, 1 = 32-bit, 2 = auto (non-indexed)
		VertexBufferTable, // 32-bit pointer to the vertex buffer descriptors, one per binding
		PushConstant,	   // a push-constant dword (PrecompiledGraphicsPipeline::pushConstants)
		DbCountControl,	   // DB_COUNT_CONTROL: z-pass counting enabled while an occlusion query is active
	};

	struct RegWrite
	{
		RegKind kind;
		RegPatch patch;
		uint32_t reg;
		uint32_t value;
	};

	// User-data registers [firstReg, firstReg + dwords) hold push-constant dwords from byteOffset.
	struct PrecompiledPushConstants
	{
		uint32_t firstReg;
		uint32_t dwords;
		uint32_t byteOffset;
	};

